// Builds what the window loads and git doesn't keep: renderer/masar.css (Tailwind CLI with the
// msar-erp.com config + globals.css, scanning renderer/) and renderer/lucide.js (the Lucide icons
// the screens use, inlined — the program must work without internet, no CDN, no web fonts).
import fs from 'fs'
import { execFileSync } from 'child_process'
import { createRequire } from 'module'
const require = createRequire(import.meta.url)
process.chdir(new URL('..', import.meta.url).pathname)

const NAMES = ['layout-dashboard', 'clipboard-list', 'clock', 'user-cog', 'settings', 'chevron-down', 'users', 'briefcase', 'building-2', 'folder-kanban', 'square-check',
  'users-round', 'globe', 'calendar-days', 'umbrella', 'plus', 'mail-open', 'activity', 'rotate-ccw', 'chart-column', 'shield-check', 'sliders-horizontal', 'fingerprint',
  'building', 'log-out', 'search', 'circle-user-round', 'map-pin', 'circle-help', 'funnel', 'external-link', 'pencil', 'trash-2', 'ellipsis-vertical', 'x', 'chevron-left',
  'chevron-right', 'chevrons-left', 'chevrons-right', 'download', 'printer', 'save', 'file-spreadsheet', 'file-text', 'upload', 'check', 'undo-2', 'refresh-cw', 'key-round',
  'lock', 'user', 'database', 'database-backup', 'book-open', 'cloud-off', 'wifi', 'alarm-clock', 'user-check', 'user-x', 'triangle-alert', 'file-minus', 'send', 'badge-check',
  'list', 'heart-handshake', 'sticky-note', 'hand', 'circle-alert', 'circle-check']
const icons = {}
for (const n of NAMES) icons[n] = fs.readFileSync(require.resolve(`lucide-static/icons/${n}.svg`), 'utf8')
  .replace(/<!--.*?-->/s, '').replace(/\s+/g, ' ').replace(/ (width|height)="24"/g, '').replace(/class="[^"]*"/, 'class="lucide"').trim()
fs.writeFileSync('renderer/lucide.js', `// generated by tools/build-ui.mjs\nconst LUCIDE = ${JSON.stringify(icons)}\n`)

execFileSync(process.execPath, [require.resolve('tailwindcss/lib/cli.js'), '-c', 'tailwind.config.ts', '-i', 'renderer/styles/app.css', '-o', 'renderer/masar.css', '--minify'], { stdio: ['ignore', 'ignore', 'inherit'] })
console.log(`ui: ${NAMES.length} icons, masar.css ${(fs.statSync('renderer/masar.css').size / 1024).toFixed(0)} KB`)
